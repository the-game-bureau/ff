function getNflWeekGames(week){
  return NFL_SCHEDULE_GAMES.filter(game => game.week === Number(week));
}

function getNflTeamGame(teamName, week){
  return getNflWeekGames(week).find(game => game.away === teamName || game.home === teamName) || null;
}

function getNflTeamOpponentName(teamName, week){
  const game = getNflTeamGame(teamName, week);
  if(!game) return '';
  return game.away === teamName ? game.home : game.away;
}

function getNflTeamLocationMark(teamName, week){
  const game = getNflTeamGame(teamName, week);
  if(!game) return 'BYE';
  return game.home === teamName ? 'vs' : '@';
}

function formatNflKickoff(kickoffUtc){
  if(!kickoffUtc) return 'TBD';
  return new Intl.DateTimeFormat('en-US', {
    timeZone: 'America/Chicago',
    weekday: 'short',
    hour: 'numeric',
    minute: '2-digit'
  }).format(new Date(kickoffUtc));
}

function getNflPickLockAtUtc(game){
  if(!game || !game.kickoffUtc) return null;
  return new Date(new Date(game.kickoffUtc).getTime() - NFL_PICK_LOCK_MINUTES * 60 * 1000).toISOString();
}

function isNflGameTbd(game){
  return !game || game.isTbd || !game.kickoffUtc;
}

function isNflTeamLocked(teamName, week, now = new Date()){
  const game = getNflTeamGame(teamName, week);
  const lockAtUtc = getNflPickLockAtUtc(game);
  return Boolean(lockAtUtc && now.getTime() >= new Date(lockAtUtc).getTime());
}

function getNflTeamScheduleInfo(teamName, week, now = new Date()){
  const game = getNflTeamGame(teamName, week);
  if(!game){
    return {
      game: null,
      opponent: '',
      homeAway: 'BYE',
      line: 'BYE',
      lockAtUtc: null,
      locked: true,
      isBye: true,
      isTbd: false
    };
  }

  const opponent = game.away === teamName ? game.home : game.away;
  const homeAway = game.home === teamName ? 'vs' : '@';
  const lockAtUtc = getNflPickLockAtUtc(game);
  const locked = isNflTeamLocked(teamName, week, now);
  const opponentShort = opponent.split(' ').slice(-1)[0];
  const time = formatNflKickoff(game.kickoffUtc);

  return {
    game,
    opponent,
    opponentShort,
    homeAway,
    line: homeAway + ' ' + opponentShort + ' - ' + time,
    lockAtUtc,
    locked,
    isBye: false,
    isTbd: isNflGameTbd(game)
  };
}

// The open week rolls over to the next one as soon as the LAST game of the
// week has kicked off. Games with no announced time (flex-scheduled weeks come
// through as TBD) are skipped rather than treated as never-starting, which
// would otherwise pin the season on the first week containing one.
function getCurrentNflWeek(now = new Date()){
  for(let week = 1; week <= 18; week++){
    const kickoffs = getNflWeekGames(week)
      .map(game => game.kickoffUtc)
      .filter(Boolean)
      .map(stamp => new Date(stamp).getTime());

    // Nothing scheduled yet for this week: it is still ahead of us.
    if(!kickoffs.length) return week;

    if(now.getTime() < Math.max(...kickoffs)) return week;
  }
  return 18;
}

function getNflScheduleUrlForWeek(week = getCurrentNflWeek()){
  return NFL_SCHEDULE_SOURCE_URL + '#week' + Number(week);
}

